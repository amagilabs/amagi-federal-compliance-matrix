"""Write the matrix as .xlsx, markdown, CSV or JSON."""

from __future__ import annotations

import csv
import io
import json
from collections import Counter
from dataclasses import dataclass, field
from datetime import date
from pathlib import Path
from typing import Dict, List, Optional, Sequence

from . import __version__
from .detect import Clause, Requirement

BASE_COLUMNS = [
    "ID", "Section", "Section Title", "UCF", "Page", "Keyword", "Kind", "Actor", "Requirement", "Refs",
]
RESPONSE_COLUMNS = ["Compliance", "Proposal Reference", "Owner", "Response / Notes"]
COMPLIANCE_CHOICES = ["Comply", "Partial", "Exception", "N/A"]
ACTORS = ["Offeror", "Contractor", "Government", "Unclear"]


@dataclass
class Matrix:
    source: str
    pages: int
    sha256: str
    requirements: List[Requirement]
    clauses: List[Clause]
    warnings: List[str] = field(default_factory=list)
    removed: List[Requirement] = field(default_factory=list)  # update mode only
    previous_source: str = ""
    extra_columns: List[str] = field(default_factory=list)  # user-added columns carried over

    @property
    def is_update(self) -> bool:
        return bool(self.previous_source)

    def columns(self) -> List[str]:
        cols = list(BASE_COLUMNS)
        if self.is_update:
            cols.insert(1, "Change")
            cols.insert(cols.index("Requirement") + 1, "Previous Text")
        return cols + RESPONSE_COLUMNS + list(self.extra_columns)

    def counts(self) -> Counter:
        return Counter(r.actor for r in self.requirements)


def _cell(req: Requirement, col: str) -> str:
    return {
        "ID": req.id, "Change": req.change, "Section": req.section, "Section Title": req.section_title,
        "UCF": req.ucf, "Page": req.page, "Keyword": req.keyword, "Kind": req.kind,
        "Actor": req.actor, "Requirement": req.text, "Previous Text": req.previous_text,
        "Refs": ", ".join(req.refs),
    }.get(col, req.responses.get(col, ""))


def summary_lines(m: Matrix) -> List[str]:
    c = m.counts()
    parts = [f"{c.get(a, 0)} {a.lower()}" for a in ACTORS if c.get(a, 0)]
    lines = [f"{len(m.requirements)} requirements: " + (", ".join(parts) if parts else "none")]
    by_ucf = Counter(r.ucf or "-" for r in m.requirements)
    if any(k != "-" for k in by_ucf):
        order = sorted(by_ucf, key=lambda k: (k == "-", k))
        lines.append("by UCF section: " + ", ".join(f"{k if k != '-' else 'other'} {by_ucf[k]}" for k in order))
    if m.clauses:
        titled = sum(1 for cl in m.clauses if cl.title)
        lines.append(f"{len(m.clauses)} FAR/DFARS clauses referenced ({titled} with titles)")
    if m.is_update:
        ch = Counter(r.change for r in m.requirements)
        lines.append(
            f"vs {m.previous_source}: {ch.get('Unchanged', 0)} unchanged, {ch.get('Changed', 0)} changed, "
            f"{ch.get('New', 0)} new, {len(m.removed)} removed; responses carried to "
            f"{sum(1 for r in m.requirements if r.change in ('Unchanged', 'Changed') and any(r.responses.values()))} rows"
        )
    return lines


# --- markdown ---------------------------------------------------------------


def _md(text: str) -> str:
    return str(text).replace("\\", "\\\\").replace("|", "\\|").replace("\n", " ")


def to_markdown(m: Matrix) -> str:
    out = io.StringIO()
    out.write(f"# Compliance matrix: {m.source}\n\n")
    out.write(
        f"Source: `{m.source}`, {m.pages} pages, sha256 `{m.sha256[:12]}`. "
        f"Generated by amagi-shall {__version__} on {date.today().isoformat()}.\n\n"
    )
    for line in summary_lines(m):
        out.write(f"- {line}\n")
    for w in m.warnings:
        out.write(f"- warning: {w}\n")
    out.write("\n")
    cols = ["ID"] + (["Change"] if m.is_update else []) + [
        "Section", "Page", "Actor", "Requirement", "Compliance", "Proposal Reference", "Response / Notes",
    ]
    out.write("| " + " | ".join(cols) + " |\n")
    out.write("|" + "|".join("---" for _ in cols) + "|\n")
    for r in m.requirements:
        out.write("| " + " | ".join(_md(_cell(r, c)) for c in cols) + " |\n")
    if m.is_update and m.removed:
        out.write(f"\n## Removed since {m.previous_source}\n\n")
        out.write("| ID | Section | Requirement | Compliance |\n|---|---|---|---|\n")
        for r in m.removed:
            out.write(f"| {_md(r.id)} | {_md(r.section)} | {_md(r.text)} | {_md(r.responses.get('Compliance', ''))} |\n")
    if m.clauses:
        out.write("\n## Clauses referenced\n\n| Clause | Title | Date | Pages |\n|---|---|---|---|\n")
        for cl in m.clauses:
            out.write(f"| {cl.number} | {_md(cl.title)} | {cl.date} | {', '.join(map(str, cl.pages))} |\n")
    return out.getvalue()


# --- csv / json -------------------------------------------------------------


def to_csv(m: Matrix) -> str:
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    cols = m.columns()
    w.writerow(cols)
    for r in m.requirements:
        w.writerow([_cell(r, c) for c in cols])
    return buf.getvalue()


def to_json(m: Matrix) -> str:
    data = {
        "tool": f"amagi-shall {__version__}",
        "source": m.source, "pages": m.pages, "sha256": m.sha256,
        "summary": summary_lines(m), "warnings": m.warnings,
        "requirements": [r.as_dict() for r in m.requirements],
        "clauses": [cl.__dict__ for cl in m.clauses],
    }
    if m.is_update:
        data["previous_source"] = m.previous_source
        data["removed"] = [r.as_dict() for r in m.removed]
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


# --- xlsx -------------------------------------------------------------------

WIDTHS = {
    "ID": 12, "Change": 11, "Section": 10, "Section Title": 24, "UCF": 6, "Page": 7, "Keyword": 11,
    "Kind": 13, "Actor": 12, "Requirement": 70, "Previous Text": 50, "Refs": 14, "Compliance": 13,
    "Proposal Reference": 20, "Owner": 14, "Response / Notes": 50,
}


def write_xlsx(m: Matrix, path: Path) -> Path:
    from openpyxl import Workbook
    from openpyxl.styles import Alignment, Font, PatternFill
    from openpyxl.utils import get_column_letter
    from openpyxl.worksheet.datavalidation import DataValidation

    wb = Workbook()
    ws = wb.active
    ws.title = "Matrix"
    cols = m.columns()
    ws.append(cols)
    head_fill = PatternFill("solid", fgColor="1F2937")
    resp_fill = PatternFill("solid", fgColor="0F766E")
    for i, col in enumerate(cols, start=1):
        cell = ws.cell(row=1, column=i)
        cell.font = Font(bold=True, color="FFFFFF")
        cell.fill = resp_fill if col in RESPONSE_COLUMNS else head_fill
        cell.alignment = Alignment(vertical="center", wrap_text=True)
        ws.column_dimensions[get_column_letter(i)].width = WIDTHS.get(col, 18)
    gov_font = Font(color="6B7280")
    for r in m.requirements:
        ws.append([_cell(r, c) for c in cols])
        row = ws.max_row
        for i, col in enumerate(cols, start=1):
            cell = ws.cell(row=row, column=i)
            cell.alignment = Alignment(vertical="top", wrap_text=col in ("Requirement", "Previous Text", "Response / Notes", "Section Title"))
            if r.actor == "Government" and col not in RESPONSE_COLUMNS:
                cell.font = gov_font
    ws.freeze_panes = "B2"
    last = get_column_letter(len(cols))
    ws.auto_filter.ref = f"A1:{last}{max(2, ws.max_row)}"
    comp_col = get_column_letter(cols.index("Compliance") + 1)
    dv = DataValidation(type="list", formula1='"' + ",".join(COMPLIANCE_CHOICES) + '"', allow_blank=True)
    dv.error = "Pick Comply, Partial, Exception or N/A"
    dv.prompt = "Comply / Partial / Exception / N/A"
    ws.add_data_validation(dv)
    dv.add(f"{comp_col}2:{comp_col}{max(2, ws.max_row) + 200}")

    if m.is_update:
        rm = wb.create_sheet("Removed")
        rcols = BASE_COLUMNS + RESPONSE_COLUMNS
        rm.append(rcols)
        for r in m.removed:
            rm.append([_cell(r, c) for c in rcols])
        for i, col in enumerate(rcols, start=1):
            rm.cell(row=1, column=i).font = Font(bold=True)
            rm.column_dimensions[get_column_letter(i)].width = WIDTHS.get(col, 18)

    cs = wb.create_sheet("Clauses")
    cs.append(["Clause", "Title", "Date", "Pages"])
    for cl in m.clauses:
        cs.append([cl.number, cl.title, cl.date, ", ".join(map(str, cl.pages))])
    for i, w in enumerate((14, 80, 11, 16), start=1):
        cs.cell(row=1, column=i).font = Font(bold=True)
        cs.column_dimensions[get_column_letter(i)].width = w

    sm = wb.create_sheet("Summary")
    sm.append(["Actor", "Requirements"])
    counts = m.counts()
    for a in ACTORS:
        sm.append([a, counts.get(a, 0)])
    sm.append([])
    sm.append(["Section", "Requirements"])
    by_sec = Counter(r.section or "-" for r in m.requirements)
    for sec in sorted(by_sec, key=_section_sort_key):
        sm.append([sec, by_sec[sec]])
    for cell in (sm["A1"], sm["B1"]):
        cell.font = Font(bold=True)
    sm.column_dimensions["A"].width = 18
    sm.column_dimensions["B"].width = 14

    ab = wb.create_sheet("About")
    rows = [
        ("Source", m.source), ("Pages", m.pages), ("SHA-256", m.sha256),
        ("Generated by", f"amagi-shall {__version__}"), ("Generated on", date.today().isoformat()),
    ]
    if m.is_update:
        rows.append(("Previous matrix", m.previous_source))
    rows += [("Summary", line) for line in summary_lines(m)]
    rows += [("Warning", w) for w in m.warnings]
    rows.append(("Note", "Rows come from the document text by rule. Check every row against the solicitation before you submit."))
    for k, v in rows:
        ab.append([k, v])
    ab.column_dimensions["A"].width = 18
    ab.column_dimensions["B"].width = 100

    path = Path(path)
    wb.save(str(path))
    return path


def _section_sort_key(sec: str):
    import re

    parts = re.split(r"[.\s]", sec)
    return [(0, int(p)) if p.isdigit() else (1, p) for p in parts]


def write_outputs(m: Matrix, out_dir: Path, stem: str, formats: Sequence[str]) -> List[Path]:
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    written: List[Path] = []
    for fmt in formats:
        target = out_dir / f"{stem}_matrix.{fmt}"
        if fmt == "xlsx":
            write_xlsx(m, target)
        elif fmt == "md":
            target.write_text(to_markdown(m), encoding="utf-8")
        elif fmt == "csv":
            target.write_text(to_csv(m), encoding="utf-8-sig")
        elif fmt == "json":
            target.write_text(to_json(m), encoding="utf-8")
        else:
            raise ValueError(f"unknown format {fmt!r}")
        written.append(target)
    return written


def read_matrix_xlsx(path: Path) -> Dict[str, object]:
    """Read a matrix workbook (ours, possibly edited) back into rows of dicts."""
    from openpyxl import load_workbook

    wb = load_workbook(str(path), read_only=True, data_only=True)
    ws = wb["Matrix"] if "Matrix" in wb.sheetnames else wb.worksheets[0]
    rows = list(ws.iter_rows(values_only=True))
    wb.close()
    if not rows:
        raise ValueError(f"{path.name}: the sheet is empty")
    header = [str(h).strip() if h is not None else "" for h in rows[0]]
    missing = [c for c in ("ID", "Requirement") if c not in header]
    if missing:
        raise ValueError(f"{path.name}: no {' or '.join(missing)} column in the first row of the Matrix sheet")
    records = []
    for raw in rows[1:]:
        if raw is None or all(v in (None, "") for v in raw):
            continue
        rec = {}
        for h, v in zip(header, raw):
            if h:
                rec[h] = "" if v is None else str(v).strip()
        if rec.get("Requirement"):
            records.append(rec)
    return {"header": header, "rows": records}


def stdout_text(m: Matrix, fmt: str) -> Optional[str]:
    return {"md": to_markdown, "csv": to_csv, "json": to_json}.get(fmt, lambda _m: None)(m)
